import assert from 'node:assert/strict'
import { test } from 'node:test'
import { join } from 'node:path'
import { chromium } from 'playwright'

const origin = 'https://ad.napovtor.ru'
const live = process.env.DEMO_LIVE === '1'
test('built partner demo: email, INN, campaign, reload and re-entry without API calls', { timeout:120_000 }, async t => {
  const browser = await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH})
  t.after(()=>browser.close())
  const context = await browser.newContext({viewport:{width:1157,height:900},reducedMotion:'reduce'})
  const unexpected = []
  await context.route('**/*',async route => {
    const req = route.request(), url = new URL(req.url())
    if (url.origin !== origin || !['GET','HEAD'].includes(req.method()) || url.pathname.startsWith('/api/')) {
      unexpected.push(req.method()+' '+url.pathname)
      return route.abort()
    }
    if (live) return route.continue()
    const file = url.pathname === '/' || /^\/(?:app|market)(?:\/|$)/.test(url.pathname) ? 'index.html' : url.pathname
    return route.fulfill({path:join('dist',file)})
  })
  const page = await context.newPage()
  page.on('pageerror',error=>unexpected.push(error.message))
  page.setDefaultTimeout(12_000)
  await page.goto(origin+'/')
  await page.getByRole('link',{name:'Войти',exact:true}).click()
  async function signIn(checkReload, tab=page, email='partner@example.test') {
    assert.equal(await tab.getByLabel('рабочая почта').inputValue(),email)
    await tab.getByRole('button',{name:'Получить тестовый код'}).click()
    const hint = tab.getByText('Введите тестовый код 123456',{exact:true})
    await hint.waitFor()
    const field = tab.getByLabel('код для демо-входа')
    const confirm = tab.getByRole('button',{name:'подтвердить',exact:true})
    if (checkReload) {
      await tab.reload()
      await hint.waitFor()
      await field.fill('000000')
      await confirm.click()
      await tab.getByRole('alert').waitFor()
    }
    await field.fill('123456')
    await confirm.click()
  }
  await signIn(true)
  assert.equal(await page.getByLabel('ИНН компании или ИП').inputValue(),'7707083893')
  await page.getByText('Кофейня на Садовой',{exact:true}).waitFor()
  await page.getByRole('button',{name:'это моя компания'}).click()
  await page.getByRole('heading',{name:'Рекламные кампании'}).waitFor()
  for (const [code,status] of [['ПРИМЕР10','На модерации'],['ПРИМЕР15','Активна'],['ПРИМЕР20','Остановлена']]) {
    await page.getByRole('row').filter({hasText:code}).getByText(status).waitFor()
  }
  assert.equal(new URL(page.url()).pathname,'/app/campaigns')
  await page.reload()
  await page.getByRole('link',{name:'Новая кампания',exact:true}).click()
  await page.getByRole('button',{name:/промокод на покупку/}).click()
  const submit = page.getByRole('button',{name:'отправить на проверку'})
  assert.ok(await submit.isDisabled())
  await page.getByRole('button',{name:'Предложить текст оффера'}).click()
  await page.getByRole('button',{name:'Использовать текст'}).click()
  assert.match(await page.getByLabel('условие для клиента').inputValue(),/15%.*800/)
  await page.getByLabel('промокод',{exact:true}).fill('DEMO2026')
  await page.getByLabel('условие для клиента').fill('На дегустацию по субботам')
  await page.getByLabel('сайт, где применить код').fill('coffee.example.test')
  await page.getByLabel('Работаю только онлайн').check()
  await page.locator('.mvp-go .bl-check__box').click()
  await submit.click()
  await page.getByRole('heading',{name:'Рекламные кампании'}).waitFor()
  const row=page.getByRole('row').filter({hasText:'DEMO2026'})
  await row.getByText('На модерации').waitFor()
  await row.getByRole('link').click()
  await page.getByRole('heading',{name:'Кампания DEMO2026'}).waitFor()
  const receipt = page.url()
  await page.reload()
  await page.getByText('только онлайн',{exact:true}).waitFor()
  for (const width of [320,390]) {
    await page.setViewportSize({width,height:844})
    const brand = await page.locator('.bl-header .brand').boundingBox()
    const actions = await page.locator('.mvp-me').boundingBox()
    assert.ok(brand.x+brand.width <= actions.x || brand.y+brand.height <= actions.y)
  }
  await page.setViewportSize({width:1157,height:900})
  if (process.env.BROWSER_REPORT_DIR) await page.screenshot({path:join(process.env.BROWSER_REPORT_DIR,'partner-demo-receipt.png')})
  await page.getByRole('link',{name:'Мои кампании',exact:true}).click()
  const link = page.getByRole('link',{name:/DEMO2026/})
  assert.equal(new URL(await link.getAttribute('href'),origin).href,receipt)
  await page.getByRole('button',{name:'выйти'}).click()
  await page.waitForURL(origin+'/')
  await page.goto(origin+'/app/?company=change')
  await signIn(false)
  await page.getByRole('heading',{name:'Рекламные кампании'}).waitFor()
  assert.equal(page.url(),origin+'/app/campaigns')
  await page.getByRole('link',{name:'Компания',exact:true}).click()
  await page.getByText('7707083893',{exact:true}).waitFor()
  assert.equal(await page.getByLabel('ИНН компании или ИП').count(),0)
  await page.getByRole('link',{name:'Мои кампании'}).click()
  await link.click()
  await page.getByRole('heading',{name:'Кампания DEMO2026'}).waitFor()
  await page.goto(origin+'/app/staff')
  await page.getByRole('heading',{name:'Рекламные кампании'}).waitFor()
  const newStaffTab = page.waitForEvent('popup')
  await page.getByRole('link',{name:'Открыть демо сотрудника'}).click()
  const staff = await newStaffTab
  staff.on('pageerror',e=>unexpected.push(e.message))
  await signIn(false,staff,'staff@example.test')
  await staff.getByRole('heading',{name:'Заявки партнёров'}).waitFor()
  assert.equal(await staff.getByRole('link',{name:'Сотрудники',exact:true}).count(),0)
  await staff.getByRole('link',{name:'Офферы',exact:true}).click()
  await staff.getByRole('searchbox',{name:'Поиск в реестре'}).fill('Флаувау')
  await staff.getByRole('row').filter({hasText:'Флаувау'}).getByRole('link').click()
  await staff.getByLabel('Краткое условие',{exact:true}).fill('Купон на корзину гортензий')
  await staff.getByRole('button',{name:'Сохранить изменения'}).click()
  await staff.getByRole('status').filter({hasText:'Изменения сохранены'}).waitFor()
  await staff.getByRole('link',{name:'Заявки',exact:true}).click()
  const staffRow = staff.getByRole('row').filter({hasText:'На дегустацию по субботам'})
  await staffRow.getByText('На модерации').waitFor()
  await staffRow.getByRole('link').click()
  await staff.locator('.staff-offer .campaign-creative__layout[data-layout=text]').waitFor()
  const visitor = await context.newPage()
  visitor.on('pageerror',e=>unexpected.push(e.message))
  await visitor.goto(origin+'/market/')
  await visitor.getByRole('searchbox',{name:'Поиск предложений'}).fill('гортензий')
  await visitor.getByText('Найдено предложений: 1',{exact:true}).waitFor()
  await visitor.getByText('Купон на корзину гортензий',{exact:true}).waitFor()
  await visitor.getByRole('button',{name:'Сбросить поиск'}).click()
  const offer=visitor.locator('.near-card').filter({hasText:'На дегустацию по субботам'})
  await visitor.locator('.near-card').first().waitFor()
  assert.equal(await offer.count(),0)
  const save=staff.getByRole('button',{name:'Сохранить проверку'})
  await staff.getByLabel('Предложение проверено').check()
  await staff.getByLabel('Идентификатор рекламы (erid)').fill('DemoErid26')
  await save.click()
  await staff.getByText('Ожидает оплаты',{exact:true}).waitFor()
  await visitor.reload()
  await visitor.locator('.near-card').first().waitFor()
  assert.equal(await offer.count(),0)
  await staff.getByLabel('Оплата подтверждена').check()
  await save.click()
  await row.getByText('Активна').waitFor()
  await offer.locator('.catalog-offer__benefit').waitFor()
  await offer.getByRole('link',{name:'Подробнее'}).click()
  await visitor.getByRole('button',{name:'Показать промокод'}).click()
  await visitor.getByText('DEMO2026',{exact:true}).waitFor()
  if (process.env.BROWSER_REPORT_DIR) await page.screenshot({path:join(process.env.BROWSER_REPORT_DIR,'partner-campaigns-active.png')})
  await staff.getByLabel('Оплата подтверждена').uncheck()
  await save.click()
  await row.getByText('Остановлена').waitFor()
  await visitor.getByRole('alert').filter({hasText:'Предложение больше недоступно'}).waitFor()
  await staff.getByRole('link',{name:'Все заявки'}).click()
  await staffRow.getByText('Остановлена').waitFor()
  if (process.env.BROWSER_REPORT_DIR) await staff.screenshot({path:join(process.env.BROWSER_REPORT_DIR,'staff-campaign-queue.png')})
  for (const width of [320,390]) {
    for (const tab of [staff,page]) {
      await tab.setViewportSize({width,height:844})
      assert.ok(await tab.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    }
  }
  assert.equal((await context.cookies()).filter(c=>c.name==='platform_session').length,0)
  assert.deepEqual(unexpected,[])
})
