/** Название страницы по адресу — чтобы помощник понимал, где сейчас пользователь. */
export function pageNameByPath(path: string | undefined): string | null {
  if (!path) return null
  const exact = PAGES.find((p) => p.path === path)
  if (exact) return exact.name
  const prefix = [...PAGES].sort((a, b) => b.path.length - a.path.length).find((p) => p.path !== '/' && path.startsWith(p.path))
  return prefix?.name ?? null
}

