/** Плоский текст оферты — для хранения версии документа, чтения в кабинете и скачивания. */
export function renderOfferText(): string {
  const lines: string[] = [
    PUBLIC_OFFER_META.title.toUpperCase(),
    `Версия ${PUBLIC_OFFER_META.version}, действует с ${PUBLIC_OFFER_META.effectiveFrom}`,
    '',
    PUBLIC_OFFER_META.disclaimer,
  ]
  OFFER_SECTIONS.forEach((section, i) => {
    lines.push('', `${i + 1}. ${section.title.toUpperCase()}`)
    section.clauses.forEach((clause, j) => lines.push(`${i + 1}.${j + 1}. ${clause}`))
  })
  return lines.join('\n')
}
