import assert from 'node:assert/strict'
import { test } from 'node:test'
import { join } from 'node:path'
import { chromium } from 'playwright'

const origin='http://cabinet.example.test'
const now=Date.now(), day=Math.floor((now+10_800_000)/86_400_000)
const records=Array.from({length:13},(_,i)=>({
  kind:'campaign',version:0,id:'fixture-'+i, code:'ТЕСТ'+i, name:'Компания '+i, title:'Предложение '+i, inn:'7707083893', email:'owner@example.test',
  contactName:'',phone:'',city:'Москва',submittedAt:now-i*86_400_000, status:['published','contract','stopped','archived','review'][i%5],channel:'online',
}))
const summary={today:day,funnel:records.map((r,i)=>({day:day-i,status:r.status,count:1})),recent:records.slice(0,5),groups:records.map((r,i)=>({day:day-i,status:r.status,channel:r.channel,count:1,verified:+['published','contract'].includes(r.status)}))}

test('cabinet dashboard controls, recovery, keyboard and mobile navigation',async t=>{
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH})
  t.after(()=>browser.close())
  const page=await browser.newPage({viewport:{width:1440,height:920},reducedMotion:'reduce'})
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  let failing=true, reportFailing=false, noLaunches=false, staff=false, drafts=[], hold
  const reportRow={id:records[0].id,title:'Скидка онлайн',code:'SALE',online:true,opens:48,reveals:0,sites:0,routes:0,marketShows:12,marketClicks:1,landingShows:8,landingClicks:2}
  const waitForRelease=new Promise(resolve=>{hold=resolve})
  await page.route('**/*',async route=>{
    const url=new URL(route.request().url())
    if(url.origin!==origin)return route.abort()
    const path=url.pathname
    if(path==='/api/mvp/drafts')return route.fulfill({json:drafts})
    if(path==='/api/mvp/notifications')return route.fulfill({json:{items:[],unread:0,more:false}})
    if(path==='/api/v4/staff/board')return route.fulfill({json:[]})
    if(path==='/api/v4/staff/dashboard')return route.fulfill({json:summary})
    if(path==='/api/mvp/session')return route.fulfill({json:{...(staff ? {role:'admin'} : {}),email:'owner@example.test',profile:{inn:'7707083893',company:'Тестовая компания',addr:''}}})
    if(path==='/api/mvp/dashboard'){await waitForRelease;return route.fulfill({json:noLaunches?{today:day,recent:[],groups:[]}:summary})}
    if(path==='/api/mvp/statistics/responses'){
      const items=(!noLaunches && url.searchParams.get('days')==='30')?[
        reportRow,
        {...reportRow,id:records[1].id,title:'Ранняя акция',opens:3,marketShows:3,marketClicks:3},
        {...reportRow,id:records[2].id,title:'Без показов',opens:0,marketShows:0,marketClicks:0},
      ]:[]
      return route.fulfill(reportFailing?{status:503,json:{message:'Нет связи'}}:{json:{since:now-86_400_000,impressionSince:now,today:day,hasCampaigns:!noLaunches,daily:items.length?[{day:day-1,opens:3,clicks:0},{day,opens:48,clicks:0}]:[],items}})
    }
    if(path==='/api/mvp/dashboard/rows'){
      await waitForRelease
      assert.equal(route.request().method(),'POST')
      const {q='',status='',days='0',sort='newest',page:requested='1'}=route.request().postDataJSON()
      if(failing)return route.fulfill({status:503,json:{message:'Временная ошибка загрузки'}})
      const filtered=(noLaunches?[]:records).filter(r=>(!Number(days)||r.submittedAt>=now-(Number(days)-1)*86_400_000) && r.code.toLowerCase().includes(q.toLowerCase())&&(!status||status===r.status))
      if(sort==='oldest')filtered.reverse()
      const page=Math.min(Number(requested),Math.max(1,Math.ceil(filtered.length/10)))
      return route.fulfill({json:{items:filtered.slice(10*(page-1),10*page),page,total:filtered.length}})
    }
    if(path.startsWith('/api/'))return route.fulfill({status:404,json:{message:'Недоступно'}})
    return route.fulfill({path:join('dist',path.startsWith('/app')?'index.html':path)})
  })
  await page.goto(origin+'/app/campaigns',{waitUntil:'domcontentloaded'})
  await page.getByText('Загружаем кампании…').waitFor()
  hold()
  await page.getByRole('alert').filter({hasText:'Временная ошибка'}).waitFor()
  failing=false
  await page.getByRole('button',{name:'Повторить'}).click()
  const table=page.getByRole('table')
  await table.getByRole('link',{name:'ТЕСТ0',exact:true}).waitFor()
  assert.equal(await page.getByRole('region',{name:'Воронка по этапам'}).count(),0)
  assert.equal(await page.getByRole('progressbar',{name:'Авторизация'}).count(),0)
  assert.equal(await page.getByRole('option',{name:'Авторизация'}).count(),0)
  const styles=await page.evaluate(async()=>{
    await document.fonts.ready
    const primary=document.querySelector('.crm-primary'), button=getComputedStyle(primary)
    const title=getComputedStyle(document.querySelector('.crm-page-heading h1'))
    return {background:button.backgroundColor,ink:button.color,radius:button.borderRadius,height:primary.offsetHeight,
      headingFont:title.fontFamily,headingWeight:title.fontWeight,buttonWeight:button.fontWeight,font:button.fontFamily,
      fonts:[...document.fonts].filter(f=>f.family.includes('BeelineSans Cabinet')&&f.status==='loaded').map(f=>f.weight).sort(),
      section:getComputedStyle(document.querySelector('.crm-table-card')).borderRadius}
  })
  assert.deepEqual({...styles,font:undefined,headingFont:undefined},{headingFont:undefined,background:'rgb(255, 200, 0)',ink:'rgb(40, 48, 63)',radius:'999px',height:44,headingWeight:'400',buttonWeight:'500',font:undefined,fonts:['400','500'],section:'40px'})
  assert.match(styles.font,/BeelineSans Cabinet/)
  assert.match(styles.headingFont,/BeelineSans Cabinet/)
  const guide=page.getByRole('button',{name:'С чего начать'})
  await guide.focus()
  await guide.press('Enter')
  const guideDialog=page.getByRole('dialog',{name:'С чего начать'})
  assert.equal(await guideDialog.getByRole('link',{name:/Подготовить предложение/}).getAttribute('href'),'/app/campaigns/formats')
  await page.keyboard.press('Control+k')
  await guideDialog.waitFor()
  await page.keyboard.press('Escape')
  await guide.and(page.locator(':focus')).waitFor()
  await page.keyboard.press('Control+k')
  await page.getByRole('textbox',{name:'Строка поиска'}).and(page.locator(':focus')).waitFor()
  await page.keyboard.press('Escape')
  const first=table.getByRole('checkbox').nth(1)
  await first.check()
  assert.ok(await table.getByRole('checkbox').first().evaluate(el=>el.indeterminate))
  await table.getByRole('checkbox').first().check()
  await page.getByText('Выбрано · 10').waitFor()
  await page.getByRole('button',{name:'Следующая страница'}).click()
  await table.getByRole('link',{name:'ТЕСТ12'}).waitFor()
  await table.getByRole('checkbox').nth(1).check()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Скачать CSV'}).click()
  assert.equal((await download).suggestedFilename(),'Кампании.csv')
  await page.getByRole('button',{name:'Снять выбор'}).click()
  await page.getByLabel('Сортировка').selectOption('oldest')
  await table.getByRole('row').nth(1).getByText('ТЕСТ12').waitFor()
  await page.getByLabel('Фильтр по статусу').selectOption('archived')
  await table.getByRole('row').nth(1).getByText('Архив').waitFor()
  await page.getByRole('searchbox').fill('без результата')
  await page.getByRole('heading',{name:'Ничего не найдено'}).waitFor()
  await page.getByRole('button',{name:'Сбросить фильтры'}).click()
  await table.getByRole('row').nth(1).waitFor()
  await page.getByRole('button',{name:'Настроить столбцы'}).click()
  await page.getByRole('dialog').getByLabel('Место покупки').check()
  await page.keyboard.press('Escape')
  await table.getByRole('columnheader',{name:'Место покупки'}).waitFor()
  await table.getByRole('row').nth(1).getByRole('button').click()
  await page.getByRole('dialog').getByRole('button',{name:'Открыть кампанию'}).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByLabel('Период обзора').count(),0)
  assert.equal(await page.getByRole('heading',{name:'последние события'}).count(),0)
  reportFailing=true
  await page.getByRole('link',{name:'статистика',exact:true}).click()
  await page.getByText('Не удалось загрузить статистику.').waitFor()
  reportFailing=false
  await page.getByRole('alert').getByRole('button',{name:'Повторить'}).click()
  await page.getByText(/За этот период нет размещений/).waitFor()
  await page.getByLabel('Период обзора').selectOption('30')
  await page.locator('.stats-kpis section').filter({hasText:'Просмотры карточек'}).getByText('51',{exact:true}).waitFor()
  assert.equal(await page.getByRole('columnheader',{name:'Маршрут',exact:true}).count(),0)
  assert.equal(await page.getByText('Лендинг',{exact:true}).count(),0)
  await page.getByRole('region',{name:'Показы на витрине'}).getByText(/^26,7\s*%$/).waitFor()
  await page.getByRole('row',{name:/Скидка онлайн/}).getByRole('cell',{name:/^8,3\s*%$/}).waitFor()
  await page.getByRole('row',{name:/Без показов/}).getByRole('cell',{name:'—',exact:true}).waitFor()
  assert.equal(await page.getByRole('heading',{name:'статусы кампаний'}).count(),0)
  await page.getByRole('heading',{name:'динамика по дням'}).waitFor()
  const reportSlider=page.getByRole('slider',{name:'День статистики по предложениям'})
  assert.match(await reportSlider.getAttribute('aria-valuetext'),/просмотры — 48/)
  await reportSlider.press('ArrowLeft')
  assert.match(await reportSlider.getAttribute('aria-valuetext'),/просмотры — 3/)
  assert.equal(await page.locator('.crm-chart').evaluate(e=>getComputedStyle(e).animationName),'none')
  const picker=page.locator('.crm-chart-picker')
  await picker.scrollIntoViewIfNeeded()
  const plot=await picker.boundingBox()
  await page.mouse.move(plot.x+plot.width-10,plot.y+plot.height/2)
  assert.match(await reportSlider.getAttribute('aria-valuetext'),/просмотры — 48/)
  await page.mouse.move(0,0)
  assert.match(await reportSlider.getAttribute('aria-valuetext'),/просмотры — 3/)
  await picker.click({position:{x:plot.width-10,y:plot.height/2}})
  await page.mouse.move(0,0)
  assert.match(await reportSlider.getAttribute('aria-valuetext'),/просмотры — 48/)
  const touch=await page.context().newCDPSession(page)
  await touch.send('Emulation.setTouchEmulationEnabled',{enabled:true})
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:plot.x+10,y:plot.y+plot.height/2}]})
  await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await page.waitForFunction(()=>document.querySelector('.crm-chart-range').getAttribute('aria-valuetext').includes('просмотры — 3'))
  await touch.send('Emulation.setTouchEmulationEnabled',{enabled:false})
  await touch.detach()
  await page.setViewportSize({width:320,height:844})
  const statsTable=page.locator('.stats-responses .crm-table-scroll')
  assert.ok(await statsTable.evaluate(el=>el.scrollWidth>el.clientWidth && el.querySelector('thead').getBoundingClientRect().height>10))
  assert.equal(await statsTable.locator('table').evaluate(el=>getComputedStyle(el).display),'table')
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.setViewportSize({width:1440,height:920})
  await page.getByRole('button',{name:'Свернуть меню'}).click()
  await page.getByRole('button',{name:'Развернуть меню'}).click()
  await page.getByRole('button',{name:'Настройки интерфейса'}).click()
  await page.getByRole('radio',{name:'Тёмное'}).check()
  await page.getByRole('radio',{name:'Компактная'}).check()
  await page.keyboard.press('Escape')
  await page.reload()
  await page.locator('.crm-shell[data-theme=invert][data-density=compact]').waitFor()
  await page.keyboard.press('Control+k')
  await page.getByLabel('Строка поиска').fill('ТЕСТ12')
  await page.getByLabel('Строка поиска').press('Enter')
  await table.getByRole('link',{name:'ТЕСТ12',exact:true}).waitFor()
  await page.locator('.crm-pagination').getByText('1–1 из 1',{exact:true}).waitFor()
  assert.equal(await table.getByRole('row').count(),2)
  assert.ok(!decodeURI(page.url()).includes('ТЕСТ12'))
  await page.getByRole('button',{name:'Последние события',exact:true}).click()
  await page.getByRole('button',{name:'Отметить прочитанными'}).click()
  assert.ok(await page.getByRole('button',{name:'Все события прочитаны'}).isDisabled())
  await page.getByRole('button',{name:'Требуют внимания'}).click()
  await page.getByRole('dialog').getByRole('link',{name:'Весь список'}).waitFor()
  await page.keyboard.press('Escape')
  await page.setViewportSize({width:320,height:844})
  await page.getByRole('button',{name:'Открыть меню'}).click()
  await page.getByRole('dialog').getByRole('link',{name:'компания',exact:true}).click()
  await page.getByRole('heading',{name:'Компания',exact:true}).waitFor()
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  noLaunches=true
  await page.goto(origin+'/app/campaigns')
  await page.getByRole('link',{name:'Создать кампанию',exact:true}).waitFor()
  assert.equal(await page.getByLabel('Фильтр по статусу').count(),0)
  await page.goto(origin+'/app/statistics')
  await page.getByRole('heading',{name:'Статистика появится после публикации'}).waitFor()
  drafts=[{id:'draft-example',title:'Первый оффер',code:'',step:1,updatedAt:now}]
  await page.reload()
  await page.getByRole('link',{name:'Продолжить черновик',exact:true}).waitFor()
  await page.goto(origin+'/app/campaigns')
  await page.getByRole('heading',{name:'черновики'}).waitFor()
  assert.equal(await page.getByRole('heading',{name:'Создайте первую кампанию'}).count(),0)
  assert.equal(await page.getByLabel('Фильтр по статусу').count(),0)
  staff=true
  await page.goto(origin+'/app/staff/')
  await guide.click()
  assert.equal(await guideDialog.getByRole('link',{name:/Проверить кампанию/}).getAttribute('href'),'/app/staff?view=list&status=review')
  assert.ok(await guideDialog.evaluate(el=>el.scrollWidth<=el.clientWidth))
  await page.keyboard.press('Escape')
  const overview=page.getByRole('slider',{name:'День запуска кампаний'})
  await overview.waitFor()
  assert.match(await overview.getAttribute('aria-valuetext'),/выбранный период — 1/)
  await overview.press('Home')
  assert.match(await overview.getAttribute('aria-valuetext'),/предыдущий период — 0/)
  await page.getByRole('button',{name:'Предыдущий период',exact:true}).click()
  assert.doesNotMatch(await overview.getAttribute('aria-valuetext'),/предыдущий период/)
  await page.getByLabel('Период обзора').selectOption('90')
  assert.equal(await overview.getAttribute('max'),'89')
  await page.getByText('Подробная аналитика',{exact:true}).click()
  await page.getByLabel('Группировка поступлений').selectOption('year')
  const arrivals=page.getByRole('slider',{name:'Период поступления кампаний'})
  await arrivals.waitFor()
  assert.equal(await arrivals.getAttribute('max'),'11')
  await arrivals.press('Home')
  assert.match(await arrivals.getAttribute('aria-valuetext'),/кампании — 0/)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  const media=await page.context().newCDPSession(page)
  const material=()=>page.locator('.crm-topbar').evaluate(el=>getComputedStyle(el).backdropFilter)
  assert.match(await material(),/blur/)
  for(const [name,value] of [['prefers-reduced-transparency','reduce'],['prefers-contrast','more'],['forced-colors','active']]){
    await media.send('Emulation.setEmulatedMedia',{features:[{name,value}]})
    assert.equal(await material(),'none')
  }
  await media.detach()
  assert.deepEqual(errors,[])
})
